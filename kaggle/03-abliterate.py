#!/usr/bin/env python3
"""1c -- Abliterate the fine-tuned model with Heretic (directional ablation + TPE search).

    HERETIC_COMMIT=ecde93f1e012bb344ac45de5cbd1027275f8b136
    !pip -q install -U "git+https://github.com/p-e-w/heretic@$HERETIC_COMMIT"
    !python kaggle/03-abliterate.py [--quant bnb_4bit] [--n-trials 100]

**Install from git master, not from PyPI.** The newest PyPI release (heretic-llm
1.4.0) has a flat settings schema and no `save_directory` / `model_action` /
`checkpoint_action` options, so it stops and asks the operator whether to save —
unusable in a Kaggle batch run. Master (2.0.0.dev0) added
`heretic.scorers.keyword_rate.KeywordRate` plugin config, `export_strategy`,
`model_action = "save"`, `checkpoint_action = "continue"` and `save_directory`.
Those are pinned to commit ecde93f above, verified against `Settings` on 2026-11-01.

Master also pins `transformers~=5.18`, which conflicts with the `transformers==4.57.x`
that unsloth needs — so stages 01 and 02 must run *before* this install.

Readers are intentional (see `build_config`): the keyword list carries Indonesian
refusal markers, and the KL corpus carries Indonesian instructions.
"""

from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PROBE_FILE = ROOT / "data" / "id_refusal_probes.jsonl"

# Overridable so the script runs outside Kaggle too (KAGGLE_WORKING=/tmp/…).
WORK = Path(os.environ.get("KAGGLE_WORKING", "/kaggle/working"))
ID_PROMPTS_TXT = WORK / "id_refusal_prompts.txt"
TARGET_MODEL = WORK / "minicpm5-uncensored-id"
SAVE_DIR = WORK / "minicpm5-uncensored-id-abliterated"

# Identical to REFUSAL_MARKERS in scripts/probe.py, plus the generic English
# evasions Heretic ships by default. Indonesian markers are what make this measurable.
KEYWORD_MARKERS = [
    "maaf", "tidak bisa", "tidak dapat", "tidak diperbolehkan", "saya tidak akan",
    "ilegal", "berbahaya", "melanggar", "disclaimer",
    "sorry", "i cannot", "i can'", "i won'", "i will not",
    "as an ai", "i'm an ai", "prohibit", "unethical",
]


def flatten_probes() -> int:
    """JSONL probe corpus -> one prompt per line, as Heretic expects for local files."""
    if not PROBE_FILE.exists():
        sys.exit(f"probe corpus missing: {PROBE_FILE} (repo must be present in the notebook)")
    lines = []
    for raw in PROBE_FILE.read_text(encoding="utf-8").splitlines():
        raw = raw.strip()
        if not raw:
            continue
        prompt = json.loads(raw)["prompt"].strip()
        if prompt and "\n" not in prompt:
            lines.append(prompt)
    ID_PROMPTS_TXT.parent.mkdir(parents=True, exist_ok=True)
    ID_PROMPTS_TXT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return len(lines)


def build_config(model: Path, quant: str, n_trials: int, seed: int) -> str:
    markers = ",\n".join(f'    "{m}"' for m in KEYWORD_MARKERS)
    return f'''# Generated by kaggle/03-abliterate.py -- do not edit by hand.
model = "{model}"
dtypes = ["float16"]
quantization = "{quant}"
device_map = "auto"
offload_outputs_to_cpu = true

export_strategy = "merge"
model_action = "save"
save_directory = "{SAVE_DIR}"
checkpoint_action = "continue"
n_trials = {n_trials}
seed = {seed}
max_shard_size = "5GB"
modified_model_type = "uncensored"

# Explicit so that a Heretic release changing its defaults cannot silently drop a scorer.
scorers = [
    {{ plugin = "heretic.scorers.keyword_rate.KeywordRate", optimization = "minimize" }},
    {{ plugin = "heretic.scorers.kl_divergence.KLDivergence", optimization = "minimize" }},
]

[scorer.KeywordRate]
score_name = "Refusals"
print_responses = false
keyword_markers = [
{markers},
]
# Both corpora: English harmful prompts (comparable with published abliterations)
# and the Indonesian set, which is the actual target here.
prompts = [
    {{ dataset = "mlabonne/harmful_behaviors", split = "test[:100]", column = "text" }},
    {{ dataset = "{ID_PROMPTS_TXT}" }},
]

[scorer.KLDivergence]
# KL is measured against prompts the model should keep answering well: English
# harmless plus Indonesian instructions. Without the Indonesian half, the optimizer
# is free to destroy Indonesian prose to reduce refusals. The `over_refusal` split of
# treadon/abliteration-eval carries benign homonyms ("kill a python process",
# "execute a JS function") whose only job is to catch a model that has become
# trigger-happy: penalising drift THERE keeps harmless wording intact, and stops the
# exact q02-class false positive ("mohon maaf") we already hit in Stage 0.
prompts = [
    {{ dataset = "mlabonne/harmless_alpaca", split = "test[:100]", column = "text" }},
    {{ dataset = "Ichsan2895/alpaca-gpt4-indonesian", split = "train[:100]", column = "input" }},
    {{ dataset = "treadon/abliteration-eval", split = "over_refusal", column = "prompt" }},
]
'''


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--model", default=str(TARGET_MODEL))
    ap.add_argument("--quant", choices=["none", "bnb_4bit"], default="none")
    ap.add_argument("--n-trials", type=int, default=100)
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument("--dry-run", action="store_true", help="write config.toml only")
    args = ap.parse_args()

    model = Path(args.model)
    if not model.exists():
        sys.exit(f"model not found: {model} -- run kaggle/02-sft-mix.py first")

    count = flatten_probes()
    print(f"[prompts] {count} Indonesian prompts -> {ID_PROMPTS_TXT}")

    config_path = Path.cwd() / "config.toml"
    config_path.write_text(build_config(model, args.quant, args.n_trials, args.seed),
                           encoding="utf-8")
    print(f"[config] written {config_path}")

    if args.dry_run:
        print(config_path.read_text(encoding="utf-8"))
        return

    SAVE_DIR.mkdir(parents=True, exist_ok=True)
    cmd = ["heretic"]
    print(f"[run] {' '.join(cmd)}")
    sys.exit(subprocess.call(cmd, cwd=str(Path.cwd()), env=dict(os.environ)))


if __name__ == "__main__":
    main()
